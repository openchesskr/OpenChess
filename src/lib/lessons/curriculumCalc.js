// 수순 문제: ucis는 학습자 수와 상대 응수가 번갈아, 마지막 학습자 수는 메이트(목표 mate)
const SEQ = (fen, say, ucis, lastMate = true) => {
  const line = [];
  for (let i = 0; i < ucis.length; i += 2) {
    const last = i + 2 >= ucis.length;
    line.push({ goal: last && lastMate ? { mate: true } : { uci: [ucis[i]] }, ...(ucis[i + 1] ? { reply: ucis[i + 1] } : {}) });
  }
  return { kind: "move", fen, say, line, hint: ucis[0] };
};
const SAFE = (fen, say, hint) => ({ kind: "move", fen, say, line: [{ goal: { safe: true } }], hint });

